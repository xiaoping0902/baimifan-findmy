const char *MFItemNameForID(uint64_t itemId) {
    int lo = 0, hi = MFItemNameCount() - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        uint64_t v = kMFItemNames[mid].id;
        if (v == itemId) return kMFItemNames[mid].name;
        if (v < itemId) lo = mid + 1; else hi = mid - 1;
    }
    return NULL;
}
